// MARK: - Semantic tokens (Asset Catalog backed — light/dark automatic)
// Xcode 16+ auto-generates Color.gsXxx from the asset catalog color sets,
// so we only declare tokens that are NOT in the catalog.
extension Color {
    /// Text/icons on **fixed** dark brand surfaces (teal hero fills, teal/amber gradient wells,
    /// `BrandPalette.Teal.s800` circles). Stays light in Dark Mode. Prefer **`gsTextInverse`**
    /// on **`gsBrandPrimary`** buttons — that color adapts (lighter in Dark Mode) and pairs with
    /// adaptive inverse text. The shopping list widget uses the same sRGB triple in
    /// `ShoppingListWidgetChrome.onDark` (widget target cannot import this module).
    static let gsTextOnBrand = Color(
        .sRGB,
        red: 0.949,
        green: 0.941,
        blue: 0.918,
        opacity: 1
    )
}

// Asset catalog colors (gsBackground, gsSurface, etc.) are auto-generated by
// Xcode 16+ and resolve in ShapeStyle contexts automatically.
// Only non-catalog tokens need a manual ShapeStyle shim.
extension ShapeStyle where Self == Color {
    static var gsTextOnBrand: Color { Color.gsTextOnBrand }
}

